function linesExact(lines) {
  return {
    id: "t-out",
    label: `Logs: ${lines.map((l) => JSON.stringify(l)).join(" · ")}`,
    kind: "consoleLinesExact",
    lines,
  };
}

function includes(id, label, pattern) {
  return { id, label, kind: "sourceIncludes", pattern };
}

function ex({
  day,
  n,
  title,
  difficulty,
  summary,
  lessonSlug,
  goal,
  constraints,
  starterCode,
  visibleTests,
  hints,
  checks,
}) {
  const id = `E-${day}${String(n).padStart(2, "0")}`;
  return {
    id,
    day,
    title,
    difficulty,
    summary,
    lessonSlug,
    goal,
    constraints,
    starterCode,
    visibleTests,
    hints,
    checks,
  };
}

